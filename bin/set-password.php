<?php
/**
 * Set the dashboard login credentials.
 *
 * Writes a gitignored auth.local.php at the project root that overrides the
 * defaults in config.php, so your real username and password hash never get
 * committed.
 *
 *   php bin/set-password.php                 prompt for username + password
 *   php bin/set-password.php admin s3cret    non-interactive
 *
 * After running, the new credentials take effect immediately.
 */

$root = dirname(__DIR__);

$username = $argv[1] ?? null;
$password = $argv[2] ?? null;

if ($username === null) {
    $username = trim((string) readline('Username: '));
}
if ($password === null) {
    // Hide the password input where the terminal supports it.
    if (function_exists('shell_exec') && stripos(PHP_OS, 'WIN') === false) {
        echo 'Password: ';
        shell_exec('stty -echo 2>/dev/null');
        $password = trim((string) fgets(STDIN));
        shell_exec('stty echo 2>/dev/null');
        echo "\n";
    } else {
        $password = trim((string) readline('Password: '));
    }
}

if ($username === '' || $password === '') {
    fwrite(STDERR, "Username and password are both required.\n");
    exit(1);
}

$hash = password_hash($password, PASSWORD_DEFAULT);
$export = "<?php\n// Generated by bin/set-password.php — do not commit.\nreturn "
    . var_export(['username' => $username, 'password_hash' => $hash, 'enabled' => true], true)
    . ";\n";

$file = $root . '/auth.local.php';
if (file_put_contents($file, $export) === false) {
    fwrite(STDERR, "Could not write $file\n");
    exit(1);
}

fwrite(STDOUT, "Wrote credentials to $file for user '$username'.\n");
fwrite(STDOUT, "These now override the defaults in config.php.\n");
